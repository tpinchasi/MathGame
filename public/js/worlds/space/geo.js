// A connected blob of n cells grown at random inside the cells allowed by ok(r, c).
function blob(n, ok, r0, c0) {
  const got = new Set([`${r0},${c0}`]);
  for (let guard = 0; got.size < n && guard < 500; guard++) {
    const [r, c] = pick([...got]).split(',').map(Number), [dr, dc] = pick([[1, 0], [-1, 0], [0, 1], [0, -1]]);
    if (ok(r + dr, c + dc)) got.add(`${r + dr},${c + dc}`);
  }
  return [...got];
}
