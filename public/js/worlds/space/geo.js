const five = (a, b) => rnd(a / 5, b / 5) * 5;
const cells = (rows, cols, r0 = 0, c0 = 0) => range(rows * cols, i => `${r0 + Math.floor(i / cols)},${c0 + (i % cols)}`);
const rectPts = (x, y, w, h) => [[x, y], [x + w, y], [x + w, y + h], [x, y + h]];
const drew = v => {
  const r = rectOf(v);
  return r ? `ציירתם מלבן ששטחו ${r.w * r.h} והיקפו ${2 * (r.w + r.h)}.` : 'הצורה שציירתם אינה מלבן מלא.';
};
// L-shape: a W×H rectangle with a w×h corner removed (top right)
